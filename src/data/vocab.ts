export const VOCAB_LIST: WordItem[] = [];
let nextId = 1;

for (let g = 1; g <= 6; g++) {
  const tier = VOCAB_TIERS[g];
  for (const ch of tier.words) {
    if (!VOCAB_LIST.some(item => item.char === ch && item.grade === g)) {
      VOCAB_LIST.push({
        id: nextId++,
        char: ch,
        pinyin: PINYIN_DICT[ch] || "",
        phrase: WORD_PHRASES[ch] || ch,
        grade: g,
        isExt: !tier.coreWords.includes(ch)
      });
    }
  }
}

export function isExtWord(grade: number, char: string): boolean {
  const tier = VOCAB_TIERS[grade];
  if (!tier) return false;
  return !tier.coreWords.includes(char) && tier.extWords.includes(char);
}

export function getWordPinyin(char: string): string {
  return PINYIN_DICT[char] || "";
}

export function getWordPhrase(char: string): string {
  return WORD_PHRASES[char] || char;
}

export function getWordDetail(char: string): WordDetail {
  const pinyin = PINYIN_DICT[char] || "";
  const phrase = WORD_PHRASES[char] || char;
  let grade = 1;
  for (let g = 1; g <= 6; g++) {
    if (VOCAB_TIERS[g].words.includes(char)) {
      grade = g;
      break;
    }
  }
  return {
    char,
    pinyin,
    phrase,
    audioPrompt: `找一找，【${char}】！${phrase}的${char}`,
    grade
  };
}
